/** Traduce ids de la base de origen a los ids creados en esta corrida. */
class MapaIds {
  private readonly ids = new Map<number, number>();

  constructor(private readonly entidad: string) {}

  registrar(origen: number | undefined, nuevo: number) {
    if (origen === undefined) throw new Error(`${this.entidad}: fila sin id de origen`);
    this.ids.set(origen, nuevo);
  }

  get(origen: number): number {
    const nuevo = this.ids.get(origen);
    if (nuevo === undefined) throw new Error(`${this.entidad} ${origen}: referencia fuera del fixture`);
    return nuevo;
  }

  opt(origen: number | null | undefined): number | undefined {
    return origen == null ? undefined : this.get(origen);
  }
}

async function resolverUsuarios(): Promise<MapaIds> {
  const usuarios = new MapaIds('usuario');
  const correos = Object.values(USUARIOS_ORIGEN);
  const encontrados = await prisma.usuario.findMany({
    where: { correo: { in: correos } },
    select: { idUsuario: true, correo: true },
  });
  const faltantes = correos.filter((correo) => !encontrados.some((u) => u.correo === correo));
  if (faltantes.length) {
    throw new Error(`Faltan usuarios (${faltantes.join(', ')}): ejecuta antes seed.ts y seed-demo.ts`);
  }
  for (const [origen, correo] of Object.entries(USUARIOS_ORIGEN)) {
    usuarios.registrar(Number(origen), encontrados.find((u) => u.correo === correo)!.idUsuario);
  }
  return usuarios;
}

async function sembrarProyecto(tx: Prisma.TransactionClient, f: FixtureProyecto, u: MapaIds): Promise<number> {
  const { idProyecto: _proyecto, ...proyecto } = f.proyecto;
  const { idProyecto } = await tx.proyecto.create({ data: { ...proyecto, creadoPor: u.get(proyecto.creadoPor) } });

  const revisionProyecto = new MapaIds('revision_proyecto');
  for (const { idRevisionProyecto, ...r } of f.revisionesProyecto ?? []) {
    const creada = await tx.revisionProyecto.create({ data: { ...r, idProyecto, idRevisor: u.opt(r.idRevisor) } });
    revisionProyecto.registrar(idRevisionProyecto, creada.idRevisionProyecto);
  }
  for (const { idMensaje: _mensaje, ...m } of f.mensajesRevision ?? []) {
    await tx.mensajeRevisionProyecto.create({
      data: { ...m, idProyecto, idRemitente: u.get(m.idRemitente), idRevision: revisionProyecto.opt(m.idRevision) },
    });
  }

  const rol = new MapaIds('rol_proyecto');
  for (const { idRolProyecto, ...r } of f.roles ?? []) {
    const creado = await tx.rolProyecto.create({ data: { ...r, idProyecto } });
    rol.registrar(idRolProyecto, creado.idRolProyecto);
  }

  const postulacion = new MapaIds('postulacion');
  for (const { idPostulacion, ...p } of f.postulaciones ?? []) {
    const creada = await tx.postulacion.create({
      data: {
        ...p,
        idUsuarioPostulante: u.get(p.idUsuarioPostulante),
        idRolProyecto: rol.get(p.idRolProyecto),
        resueltaPor: u.opt(p.resueltaPor),
      },
    });
    postulacion.registrar(idPostulacion, creada.idPostulacion);
  }

  const participacion = new MapaIds('participacion_proyecto');
  for (const { idParticipacion, ...p } of f.participaciones ?? []) {
    const creada = await tx.participacionProyecto.create({
      data: {
        ...p,
        idUsuario: u.get(p.idUsuario),
        idRolProyecto: rol.get(p.idRolProyecto),
        idPostulacion: postulacion.opt(p.idPostulacion),
      },
    });
    participacion.registrar(idParticipacion, creada.idParticipacion);
  }

  for (const { idSolicitud: _solicitud, ...s } of f.solicitudesSalida ?? []) {
    await tx.solicitudSalidaProyecto.create({
      data: { ...s, idProyecto, idUsuario: u.get(s.idUsuario), resueltaPor: u.opt(s.resueltaPor) },
    });
  }

  const sprint = new MapaIds('sprint');
  for (const { idSprint, ...s } of f.sprints ?? []) {
    const creado = await tx.sprint.create({ data: { ...s, idProyecto, cerradoPor: u.opt(s.cerradoPor) } });
    sprint.registrar(idSprint, creado.idSprint);
  }

  const tarea = new MapaIds('tarea');
  for (const { idTarea, ...t } of f.tareas ?? []) {
    const creada = await tx.tarea.create({
      data: {
        ...t,
        idProyecto,
        idRolProyecto: rol.opt(t.idRolProyecto),
        idSprint: sprint.opt(t.idSprint),
        creadaPor: u.get(t.creadaPor),
      },
    });
    tarea.registrar(idTarea, creada.idTarea);
  }

  const asignacion = new MapaIds('asignacion_tarea');
  for (const { idAsignacion, ...a } of f.asignaciones ?? []) {
    const creada = await tx.asignacionTarea.create({
      data: {
        ...a,
        idTarea: tarea.get(a.idTarea),
        idUsuario: u.get(a.idUsuario),
        idParticipacion: participacion.opt(a.idParticipacion),
        asignadoPor: u.get(a.asignadoPor),
      },
    });
    asignacion.registrar(idAsignacion, creada.idAsignacion);
  }
  for (const { idRegistroAvance: _avance, ...r } of f.registrosAvance ?? []) {
    await tx.registroAvanceAsignacion.create({
      data: { ...r, idAsignacion: asignacion.get(r.idAsignacion), idAutor: u.get(r.idAutor) },
    });
  }
  for (const { idRegistroTiempo: _tiempo, ...r } of f.registrosTiempo ?? []) {
    await tx.registroTiempoTarea.create({
      data: {
        ...r,
        idAsignacion: asignacion.get(r.idAsignacion),
        idUsuario: u.get(r.idUsuario),
        revocadoPor: u.opt(r.revocadoPor),
      },
    });
  }
  // En orden de id: el ajuste anulado siempre precede a su sucesor (s7_ajuste_vigente).
  const ajuste = new MapaIds('ajuste_hora_tarea');
  for (const { idAjusteHora, ...a } of f.ajustesHora ?? []) {
    const creado = await tx.ajusteHoraTarea.create({
      data: {
        ...a,
        idAsignacion: asignacion.get(a.idAsignacion),
        idAutor: u.get(a.idAutor),
        anuladoPor: u.opt(a.anuladoPor),
        idAjusteAnterior: ajuste.opt(a.idAjusteAnterior),
      },
    });
    ajuste.registrar(idAjusteHora, creado.idAjusteHora);
  }

  const apelacion = new MapaIds('apelacion_liderazgo');
  for (const { idApelacion, ...a } of f.apelaciones ?? []) {
    const creada = await tx.apelacionLiderazgo.create({
      data: {
        ...a,
        idProyecto,
        idLiderSolicitante: u.get(a.idLiderSolicitante),
        idCandidatoPropuesto: u.get(a.idCandidatoPropuesto),
        idAdminResolutor: u.opt(a.idAdminResolutor),
      },
    });
    apelacion.registrar(idApelacion, creada.idApelacion);
  }
  for (const { idHistorialLiderazgo: _historial, ...h } of f.historialLiderazgo ?? []) {
    await tx.historialLiderazgo.create({
      data: {
        ...h,
        idProyecto,
        idLiderAnterior: u.get(h.idLiderAnterior),
        idLiderNuevo: u.get(h.idLiderNuevo),
        idAdminResponsable: u.get(h.idAdminResponsable),
        idApelacion: apelacion.opt(h.idApelacion),
      },
    });
  }

  // Ninguna revisión del snapshot está APROBADA, así que ninguna enlaza un
  // informe oficial (s7_ck_20) y se pueden crear antes que sus documentos.
  const revisionCierre = new MapaIds('revision_cierre_proyecto');
  for (const { idRevisionCierre, ...r } of f.revisionesCierre ?? []) {
    const creada = await tx.revisionCierreProyecto.create({
      data: { ...r, idProyecto, idSolicitante: u.opt(r.idSolicitante), idRevisor: u.opt(r.idRevisor) },
    });
    revisionCierre.registrar(idRevisionCierre, creada.idRevisionCierre);
  }
  const documento = new MapaIds('documento_cierre');
  for (const { idDocumentoCierre, ...d } of f.documentosCierre ?? []) {
    const creado = await tx.documentoCierre.create({
      data: { ...d, idProyecto, idRevisionOrigen: revisionCierre.get(d.idRevisionOrigen), idAutor: u.get(d.idAutor) },
    });
    documento.registrar(idDocumentoCierre, creado.idDocumentoCierre);
  }
  for (const { idDocumentoRevision: _vinculo, ...d } of f.documentosRevisionCierre ?? []) {
    await tx.documentoRevisionCierre.create({
      data: {
        ...d,
        idRevisionCierre: revisionCierre.get(d.idRevisionCierre),
        idDocumentoCierre: documento.get(d.idDocumentoCierre),
      },
    });
  }

  for (const { idRegistroHoras: _horas, ...h } of f.horasParticipacion ?? []) {
    await tx.horasParticipacion.create({
      data: {
        ...h,
        idParticipacion: participacion.get(h.idParticipacion),
        aprobadoPor: u.opt(h.aprobadoPor),
        idSprint: sprint.opt(h.idSprint),
      },
    });
  }

  return idProyecto;
}

